@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ShayarAuthSheet(
    localAccount: LocalShayarAccount,
    errorMessage: String? = null,
    showGoogleSignIn: Boolean = true,
    isGoogleLoading: Boolean = false,
    onClearError: () -> Unit = {},
    onRegisterSubmit: (
        fullName: String,
        username: String,
        contact: String,
        password: String,
        bio: String,
        socialLinks: SocialLinks
    ) -> Unit,
    onLoginSubmit: (identifier: String, password: String) -> Unit,
    onResetPasswordSubmit: ((newPassword: String) -> Unit)? = null,
    onGoogleSignInClick: () -> Unit,
    onDismiss: () -> Unit
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        containerColor = MaterialTheme.colorScheme.surfaceContainerLow
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .navigationBarsPadding()
                .imePadding()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 20.dp)
                .padding(bottom = 24.dp)
                .testTag("shayar_auth_sheet"),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Box(
                    modifier = Modifier
                        .size(44.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.primaryContainer),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = Icons.Rounded.AutoAwesome,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.primary,
                        modifier = Modifier.size(22.dp)
                    )
                }
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = stringResource(R.string.auth_sheet_title),
                        style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold),
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Text(
                        text = "सिर्फ़ 10 सेकंड में रजिस्टर या लॉगिन करें ✨",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                }
                IconButton(
                    onClick = onDismiss,
                    modifier = Modifier
                        .minimumInteractiveComponentSize()
                        .testTag("auth_close_button")
                ) {
                    Icon(
                        imageVector = Icons.Rounded.Close,
                        contentDescription = stringResource(R.string.action_cancel),
                        tint = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }

            ShayarAuthFormContent(
                localAccount = localAccount,
                errorMessage = errorMessage,
                showGoogleSignIn = showGoogleSignIn,
                isGoogleLoading = isGoogleLoading,
                onClearError = onClearError,
                onRegisterSubmit = onRegisterSubmit,
                onLoginSubmit = onLoginSubmit,
                onResetPasswordSubmit = onResetPasswordSubmit,
                onGoogleSignInClick = onGoogleSignInClick
            )
        }
    }
}
